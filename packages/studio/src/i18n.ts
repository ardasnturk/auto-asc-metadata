const DICTS: Record<string, Record<UiKey, string>> = { en: EN, tr: TR };

let current: Record<UiKey, string> = EN;
export function setLanguage(tag: string | null | undefined): void {
  const base = (tag ?? 'en').split('-')[0]!.toLowerCase();
  current = DICTS[base] ?? EN;
}

export function t(key: UiKey, values: Record<string, string | number> = {}): string {
  return (current[key] ?? EN[key] ?? key).replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}
