import { ensureDir, exec, existsSync, log, TEMPLATES_DIR, writeText, type AppPaths } from '@vitrin/core';
import type { AppMetadata, LocaleMetadata, VitrinConfig } from '@vitrin/schemas';
import { copyFile, readdir, readFile, rm } from 'node:fs/promises';
import { join } from 'node:path';

/** deliver's per-locale file names (fastlane/metadata/<locale>/<name>.txt). */
export const LOCALE_FILES: Record<string, (m: LocaleMetadata, c: VitrinConfig) => string | undefined> = {
  'name.txt': (m) => m.name,
  'subtitle.txt': (m) => m.subtitle,
  'description.txt': (m) => m.description,
  'keywords.txt': (m) => m.keywords,
  'promotional_text.txt': (m) => m.promotionalText,
  'release_notes.txt': (m) => m.whatsNew || undefined,
  'support_url.txt': (m, c) => m.supportUrl ?? c.urls.support,
  'marketing_url.txt': (m, c) => m.marketingUrl ?? c.urls.marketing,
  'privacy_url.txt': (m, c) => m.privacyUrl ?? c.urls.privacy,
};

/** Optional fields that must be cleared remotely when emptied locally (release notes stay absent: first versions reject them). */
const CLEARABLE = new Set(['subtitle.txt', 'promotional_text.txt', 'marketing_url.txt']);

/**
 * Writes the deliver metadata tree. Demo account credentials are NOT written to disk:
 * the Fastfile reads them from REVIEW_DEMO_USER / REVIEW_DEMO_PASSWORD at upload time.
 */
export async function exportFastlaneMetadata(paths: AppPaths, config: VitrinConfig, app: AppMetadata, locales: LocaleMetadata[]): Promise<string[]> {
  const root = paths.fastlaneMetadata;
  const written: string[] = [];
  const write = async (rel: string, value: string | undefined, clearable = false) => {
    const file = join(root, rel);
    if (value === undefined || value === '') {
      // A missing file means "leave the remote value alone" to deliver; an empty file clears it.
      if (clearable) await writeText(file, '');
      else if (existsSync(file)) await rm(file);
      return;
    }
    await writeText(file, value.trim() + '\n');
    written.push(file);
  };
  await ensureDir(root);
  for (const m of locales) {
    // Remove files of fields that became empty so deliver does not upload stale text.
    for (const [file, get] of Object.entries(LOCALE_FILES)) await write(join(m.locale, file), get(m, config), CLEARABLE.has(file));
  }
  await write('copyright.txt', app.copyright);
  await write('primary_category.txt', app.primaryCategory);
  await write('secondary_category.txt', app.secondaryCategory);
  await write('primary_first_sub_category.txt', app.primarySubcategories[0]);
  await write('primary_second_sub_category.txt', app.primarySubcategories[1]);
  await write('secondary_first_sub_category.txt', app.secondarySubcategories[0]);
  await write('secondary_second_sub_category.txt', app.secondarySubcategories[1]);
  const r = config.review;
  await write('review_information/first_name.txt', r.firstName);
  await write('review_information/last_name.txt', r.lastName);
  await write('review_information/phone_number.txt', r.phone);
  await write('review_information/email_address.txt', r.email);
  await write('review_information/notes.txt', app.reviewNotes);
  for (const legacy of ['demo_user.txt', 'demo_password.txt']) {
    const f = join(root, 'review_information', legacy);
    if (existsSync(f)) {
      await rm(f);
      log.warn(`${legacy} deleted: demo account credentials are never stored in files; .env (REVIEW_DEMO_*) is used instead.`);
    }
  }
  return written;
}

/** `# vitrin-template: N` marker in the Fastfile template; files without it are version 1. */
export function templateVersion(text: string): number {
  return Number(/^# vitrin-template: (\d+)/m.exec(text)?.[1] ?? 1);
}

/** Copies Gemfile + Fastfile templates into the app repo (never overwrites a user-edited Fastfile without --force). */
export async function installFastlaneTemplates(paths: AppPaths, force = false): Promise<string[]> {
  const out: string[] = [];
  await ensureDir(paths.fastlane);
  const pairs: Array<[string, string]> = [
    [join(TEMPLATES_DIR, 'Gemfile'), join(paths.root, 'Gemfile')],
    [join(TEMPLATES_DIR, 'Fastfile'), join(paths.fastlane, 'Fastfile')],
  ];
  for (const [src, dest] of pairs) {
    if (existsSync(dest) && !force) {
      const cur = await readFile(dest, 'utf8');
      if (dest.endsWith('Gemfile') && !/fastlane/.test(cur)) {
        log.warn('The existing Gemfile does not include fastlane; add the line `gem "fastlane", ">= 2.241.1"`.');
      } else if (dest.endsWith('Fastfile') && !cur.includes('vitrin_upload')) {
        log.warn('The existing Fastfile has no vitrin lanes; the template was written to fastlane/Fastfile.vitrin, import it (import "Fastfile.vitrin").');
        await copyFile(src, `${dest}.vitrin`);
        out.push(`${dest}.vitrin`);
      } else if (dest.endsWith('Fastfile') && cur.startsWith('# Generated by Vitrin') && templateVersion(cur) < templateVersion(await readFile(src, 'utf8'))) {
        // An older generated Fastfile (no platform parameter, no supply lane): keep a backup and refresh it.
        await copyFile(dest, `${dest}.bak`);
        await copyFile(src, dest);
        log.warn('fastlane/Fastfile was generated by an older Vitrin; it was refreshed (backup: fastlane/Fastfile.bak).');
        out.push(dest);
      }
      continue;
    }
    await copyFile(src, dest);
    out.push(dest);
  }
  return out;
}

export interface LaneEnv {
  bundleId: string;
  languages: string[];
  appVersion?: string;
  /** deliver platform: ios | osx | appletvos | xros. */
  platform: string;
  /**
   * The Fastfile always uploads with overwrite_screenshots/overwrite_preview_videos, which delete every set of each
   * locale that has files; callers put only complete sets into `screenshotsPath`/`previewsPath` (see scope.ts).
   */
  skipScreenshots?: boolean;
  skipMetadata?: boolean;
  /** Per-platform folders from buildDeliverFolders; the Fastfile falls back to fastlane/{metadata,screenshots,app-previews}. */
  metadataPath?: string;
  screenshotsPath?: string;
  previewsPath?: string;
}

/** Injected in tests; defaults to the masking `exec` from @vitrin/core. */
export type CommandRunner = typeof exec;

export interface LaneInvocation {
  command: string;
  args: string[];
  env: Record<string, string>;
}

const FASTLANE_QUIET_ENV = { FASTLANE_SKIP_UPDATE_CHECK: '1', FASTLANE_HIDE_CHANGELOG: '1', FASTLANE_DISABLE_COLORS: '1' };

/** `bundle exec fastlane ios <lane> platform:<p>` plus the VITRIN_* variables the Fastfile reads. */
export function deliverLaneInvocation(lane: string, env: LaneEnv): LaneInvocation {
  return {
    command: 'bundle',
    args: ['exec', 'fastlane', 'ios', lane, `platform:${env.platform}`],
    env: {
      VITRIN_BUNDLE_ID: env.bundleId,
      VITRIN_LANGUAGES: env.languages.join(','),
      VITRIN_APP_VERSION: env.appVersion ?? '',
      VITRIN_PLATFORM: env.platform,
      VITRIN_SKIP_SCREENSHOTS: env.skipScreenshots ? '1' : '0',
      VITRIN_SKIP_METADATA: env.skipMetadata ? '1' : '0',
      VITRIN_METADATA_PATH: env.metadataPath ?? '',
      VITRIN_SCREENSHOTS_PATH: env.screenshotsPath ?? '',
      VITRIN_PREVIEWS_PATH: env.previewsPath ?? '',
      ...FASTLANE_QUIET_ENV,
    },
  };
}

export interface SupplyLaneEnv {
  packageName: string;
  /** fastlane/metadata/android (absolute). */
  metadataPath: string;
  /** Track whose existing release supply reads; never changed. */
  track: string;
  versionCode?: number;
  /** supply validate_only: the edit is validated by Google Play and discarded, nothing is published. */
  validateOnly: boolean;
  /** Absolute path of the service account JSON key. Not needed when GOOGLE_PLAY_JSON_KEY_BASE64 is set (read by the Fastfile). */
  jsonKeyPath?: string;
  /** Listing text (title, descriptions, video). */
  skipMetadata?: boolean;
  /** Release notes of versionCode (always skipped without a versionCode). */
  skipChangelogs?: boolean;
  /** Feature graphic and icon. supply only replaces image types that have local files. */
  skipImages?: boolean;
  skipScreenshots?: boolean;
}

/**
 * `bundle exec fastlane android vitrin_play_upload`. The key content is never put on the command line or into
 * this env map: with GOOGLE_PLAY_JSON_KEY_BASE64 the Fastfile decodes it from the inherited environment.
 */
export function supplyLaneInvocation(env: SupplyLaneEnv): LaneInvocation {
  return {
    command: 'bundle',
    args: ['exec', 'fastlane', 'android', 'vitrin_play_upload', ...(env.validateOnly ? ['validate_only:true'] : [])],
    env: {
      VITRIN_PLAY_PACKAGE_NAME: env.packageName,
      VITRIN_PLAY_METADATA_PATH: env.metadataPath,
      VITRIN_PLAY_TRACK: env.track,
      VITRIN_PLAY_VERSION_CODE: env.versionCode ? String(env.versionCode) : '',
      VITRIN_PLAY_VALIDATE_ONLY: env.validateOnly ? '1' : '0',
      VITRIN_PLAY_JSON_KEY_PATH: env.jsonKeyPath ?? '',
      VITRIN_PLAY_SKIP_METADATA: env.skipMetadata ? '1' : '0',
      VITRIN_PLAY_SKIP_CHANGELOGS: env.skipChangelogs || !env.versionCode ? '1' : '0',
      VITRIN_PLAY_SKIP_IMAGES: env.skipImages ? '1' : '0',
      VITRIN_PLAY_SKIP_SCREENSHOTS: env.skipScreenshots ? '1' : '0',
      ...FASTLANE_QUIET_ENV,
    },
  };
}

async function ensureBundle(paths: AppPaths, runner: CommandRunner): Promise<void> {
  const gemfile = join(paths.root, 'Gemfile');
  if (!existsSync(gemfile)) throw new Error('No Gemfile; `vitrin init` installs the fastlane templates.');
  const check = await runner('bundle', ['check'], { cwd: paths.root });
  if (check.code !== 0) {
    log.step('bundle install (fastlane >= 2.241.1)…');
    const res = await runner('bundle', ['install'], { cwd: paths.root, stream: true });
    if (res.code !== 0) throw new Error('bundle install failed.');
  }
}

/** Runs `bundle exec fastlane android vitrin_play_upload` (metadata and images only, never a release). */
export async function runSupplyLane(paths: AppPaths, env: SupplyLaneEnv, runner: CommandRunner = exec): Promise<void> {
  await ensureBundle(paths, runner);
  const inv = supplyLaneInvocation(env);
  const res = await runner(inv.command, inv.args, { cwd: paths.root, stream: true, env: inv.env });
  if (res.code !== 0) {
    const text = res.stdout + res.stderr;
    if (/Unable to find the requested track|Could not find release for version code/i.test(text)) {
      throw new Error(`supply needs an existing release on the “${env.track}” track to update the listing (it reads the release even for metadata-only runs). Upload a build once in Play Console, or set track/versionCode in .vitrin/metadata/play/app.json.`);
    }
    if (/More than one release found/i.test(text)) throw new Error('The track has more than one release; set versionCode in .vitrin/metadata/play/app.json.');
    if (/Package not found|applicationNotFound/i.test(text)) throw new Error(`Google Play has no app ${env.packageName}; the app must be created once in Play Console (the API cannot create apps).`);
    if (/\b403\b|The caller does not have permission|forbidden/i.test(text)) throw new Error('Google Play refused the service account (403). Invite it in Play Console > Users and permissions with “Edit store listing” for this app.');
    throw new Error(`fastlane vitrin_play_upload failed (exit ${res.code}). See the details above.`);
  }
}

/** Runs `bundle exec fastlane ios <lane> platform:<p>` in the app root, installing gems first if needed. */
export async function runLane(paths: AppPaths, lane: string, env: LaneEnv, runner: CommandRunner = exec): Promise<void> {
  await ensureBundle(paths, runner);
  const inv = deliverLaneInvocation(lane, env);
  const res = await runner(inv.command, inv.args, { cwd: paths.root, stream: true, env: inv.env });
  if (res.code !== 0) {
    const text = res.stdout + res.stderr;
    if (/deprecat|appScreenshotSets|appPreviewSets|410 Gone/i.test(text)) {
      throw new Error('fastlane failed on the legacy media endpoints (ASC API 4.5.1 deprecation). Retry with `vitrin upload --uploader=asset-library`.');
    }
    if (/Could not find (a )?version|no editable|cannot create.*version/i.test(text)) {
      throw new Error('No editable App Store version. Create the first version once in App Store Connect, then say “continue”.');
    }
    throw new Error(`fastlane ${lane} failed (exit ${res.code}). See the details above.`);
  }
}

export async function listScreenshotFiles(dir: string): Promise<string[]> {
  if (!existsSync(dir)) return [];
  return (await readdir(dir)).filter((f) => /\.(png|jpe?g)$/i.test(f)).sort();
}
